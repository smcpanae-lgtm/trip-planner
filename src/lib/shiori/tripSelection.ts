/**
 * AI旅行記（/shiori）で「どの記録を旅行記の対象にするか」を決める定数。
 *
 * サーバー（/api/generate）・しおり画面（ShioriClient）・人生体験マップの
 * 旅行グループ表示（lib/lifemap/tripGroups）の3か所が同じ値を必要とするため、
 * ここを唯一の定義元にしている。値を変えるときはこのファイルだけを直す。
 */

/**
 * 一度にAI生成できる記録の上限。
 *
 * サーバーはこれを超えるリクエストを errorCode: "too_many_entries" で拒否し、
 * クライアントは既定の選択をこの件数で打ち切る。両者がずれると
 * 「選べるのに生成できない」状態になるため、必ず同じ値を参照させる。
 */
export const MAX_AI_SPOTS = 20;

/**
 * 「1回の旅行」とみなす日数の幅。
 * 4日 ＝ 最大3泊4日。国内旅行は1泊2日〜3泊4日が主流で、
 * 「2泊3日で5〜8か所まわる」使い方は確実に収まる。
 * 5日以上に広げると、旅行から帰った翌日に近所で撮った記録まで混ざりやすくなる。
 *
 * 【この値の使われ方が2か所で異なることに注意】
 *
 * - /shiori（pickRecentTrip）: 最新の記録の日付から遡る「固定窓」。
 *   ids= なしで開いたときの既定選択に使う。10日間の旅行でも末尾4日ぶんしか選ばない。
 *   クラスタ方式を採らなかった理由は pickRecentTrip のコメントを参照。
 * - /life-map（groupEntriesIntoTrips）: 隣接する記録の間隔で切る「連鎖」。
 *   毎日記録があれば10日間の旅行がひとつのグループになる。
 *
 * したがって、マップ側で見えているグループと、/shiori を ids= なしで開いたときの
 * 既定選択は一致しないことがある。マップのボタンは ids= を明示で渡し、
 * /shiori 側は ids= があれば全選択するため、実際の動作に食い違いは出ない。
 * どちらかの方式を変えるときは、この差異が意図的なものであることを踏まえて判断すること。
 */
export const TRIP_WINDOW_DAYS = 4;
